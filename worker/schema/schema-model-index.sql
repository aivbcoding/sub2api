-- ============================================================
-- 新增: 账号模型索引 (accounts.model_index) —— 「新模型自动归到中转」
--
-- 背景: 之前平台是按**模型名推断**的 (glm->zhipu, kimi->kimi)。接入中转上游后
-- 这个假设不成立 —— 中转上的 `glm-*` 由哪个平台账号服务是账号自己的事实, 不是
-- 名字能猜的。猜错就去找一个没有账号的平台, 请求 503 no_upstream_account。
--
-- 现在改为**事实驱动**:
--   1. 后台「模型获取」把上游真实返回的模型 ID 列表写进本列 (JSON 数组)
--   2. 网关路由时, 请求的模型名出现在哪个账号的索引里, 就发到那个账号的平台
--   => 新模型 (如 glm-4.6) 无需任何配置即可自动归到中转, 不会再按名字跑官方。
--
-- 格式: JSON 数组, 元素是**对外模型名**, 例: ["glm-5.2","glm-4.6","deepseek-v4-pro"]
-- 空数组是有效状态(表示"该上游没有模型"), 会覆盖旧值。
--
-- 兼容性: 该列不存在时网关会退化为"没有索引"(按路径兜底), 不会报错 ——
-- 因此这条迁移可以在任意时刻执行, 不会打挂线上流量。
--
-- 用法: npx wrangler d1 execute sub2api --file=./schema/schema-model-index.sql --remote -y
-- ============================================================

ALTER TABLE accounts ADD COLUMN model_index TEXT;
